-- migration_067_master_occasions.sql
-- ربط المتجر بمواسم التخفيضات صراحةً بدل استنتاجه من التصنيف.
--
-- Why (المشكلة الجذرية، 2026-08-01):
--   صفحات المناسبات (/back-to-school, /national-day) كانت تستنتج «هل هذا المتجر
--   يخصّ الموسم؟» من `master.store_tags` — وهي مفردات **تصنيف كتالوج** لا مفردات
--   موسم. النتيجة عيبان متعاكسان لا يمكن حلّهما بأي قاعدة وسوم:
--     • إيجابيات كاذبة: وسم عام مثل `إكسسوارات` يعني جرابات جوال عند متجر وذهباً
--       عند آخر، فدخلت ١١ متجر عبايات/مجوهرات صفحةَ العودة للمدارس.
--     • سلبيات كاذبة: «مرايا ابداع» يبيع «توزيعات مدارس وجامعات» — مدرسيّ فعلاً —
--       لكن وسمه الصحيح `هدايا/توزيعات`. وسمه بـ`الكتب و التعليم` كان سيُصلح صفحة
--       الموسم ويُفسد صفحة القسم بمتجر لا يبيع كتباً.
--   العمودان يخدمان وظيفتين مختلفتين، فيلزم عمود ثانٍ لا وسم مُقحَم.
--
-- الشكل: TEXT بصيغة مصفوفة نصية `'{a,b}'` — **نفس اصطلاح `store_tags`** عن قصد،
-- ليقرأه/يكتبه الداشبورد والـAPI بنفس دوال التحويل الموجودة. (تحويله لـ`text[]`
-- حقيقي يخصّ دَيْن النوع العام في db_foundation_audit، لا هذه المايقريشن.)
--
-- القيم = معرّفات المواسم في `app/calendar/data.ts` (SALE_SEASONS[].id) بالإنجليزية:
--   winter-clearance, founding-day, ramadan, eid-fitr, eid-adha, summer-sale,
--   back-to-school, national-day, riyadh-season, eleven-eleven, white-friday,
--   twelve-twelve
--
-- الدلالة: **إضافة فقط.** صفحة الموسم تعرض (المتاجر المطابقة لوسوم الموسم) ∪
-- (المتاجر المؤشَّرة هنا صراحةً). فارغ = السلوك الحالي بلا تغيير، فالمايقريشن
-- آمنة رجعياً ولا تُخفي أي متجر معروض اليوم.

ALTER TABLE master ADD COLUMN IF NOT EXISTS occasions TEXT;

COMMENT ON COLUMN master.occasions IS
  'مواسم يظهر فيها المتجر صراحةً، بصيغة {slug,slug} من SALE_SEASONS ids. إضافة فوق استنتاج store_tags، لا بديل عنه.';

-- فهرس بحث نصّي بسيط: صفحات المناسبات تستعلم بـILIKE ''%slug%'' على عمود نصّي.
-- (لا GIN — العمود نصّ لا مصفوفة، والكتالوج بعشرات الصفوف لا ملايينها.)
CREATE INDEX IF NOT EXISTS idx_master_occasions
    ON master (occasions)
    WHERE occasions IS NOT NULL AND occasions <> '';
