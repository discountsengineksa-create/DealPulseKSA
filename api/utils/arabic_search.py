def build_seed_rows() -> list[tuple[str, str, float]]:
    """يفكّ CONCEPT_SEED إلى صفوف (term_norm, canonical_tag, weight) بلا تكرار.

    يُستعمل من scripts/gen_migration_070.py لتوليد جُمَل الإدراج،
    ومن الاختبارات للتحقّق من أن كل canonical_tag موجود فعلاً في الكتالوج.
    """
    seen: set[tuple[str, str]] = set()
    rows: list[tuple[str, str, float]] = []

    def _add(term: str, tag: str, weight: float) -> None:
        term = normalize_ar(term)
        if len(term) < 2:
            return
        key = (term, tag)
        if key in seen:
            return
        seen.add(key)
        rows.append((term, tag, weight))

    for raw_term, targets in CONCEPT_SEED.items():
        for tag, weight in targets:
            _add(raw_term, tag, weight)
            # صفّ الهويّة: الوسم نفسه مطبّعاً يطابق نفسه بوزن كامل، حتى يجد
            # الباحث «ازياء» القسمَ «أزياء» بلا مرادف صريح في القاموس.
            _add(tag, tag, 1.0)

    return rows
